CREATE TABLE evento_game_loop(
  fk_evento int generated by default as identity primary key,
  id_partida int not null,
  dia_virtual int not null,
  descricao_evento varchar(255) not null,
  data_evento timestamp
);


drop table configuracao_jogo;



CREATE TABLE configuracao_jogo(
  id_configuracao int generated by default as identity primary key,
  fk_jogador int not null,
  volume_geral int,
  volume_musica int,
  volume_sfx int,
  resolucao_tela varchar(20),
  modo_janela boolean,
  sensibilidade_mouse decimal(5,2),
  data_ultima_atualizacao timestamp,
  constraint fk_jogador foreign key (fk_jogador) references jogador (id_jogador)
);


drop table partida;

CREATE TABLE partida (
id_partida INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
fk_recurso_cenario INT NOT NULL,
dias_sobrevividos INT,
tempo_jogado_segundos INT,
resultado VARCHAR(50) NOT NULL,
causa_morte VARCHAR(50),
data_inicio TIMESTAMP,
data_fim TIMESTAMP,
constraint fk_recurso_cenario foreign key (fk_recurso_cenario) references recurso_cenario (id_recurso)
);

drop table item_catalogo;

CREATE TABLE item_catalogo (
id_item int generated by default as identity primary key ,
fk_inventario_item int not null,
nome varchar(100) not null,
categoria varchar(50) not null,
peso_unitario decimal(5,2) not null,
recuperacao_vida decimal(5,2),
recuperacao_fome decimal(5,2),
recuperacao_sede decimal(5,2)
constraint fk_inventario_item foreign key (fk_inventario_item) references inventario (id_inventario)
);



CREATE TABLE telemetria_partida (
id_telemetria int generated by default as identity primary key,
id_partida int not null,
fps_medio int,
input_lag_ms int,
itens_coletados_total int,
data_registro timestamp
);


drop table recurso_cenario;


CREATE TABLE recurso_cenario (
id_recurso int generated by default as identity primary key,
fk_inventario_item int not null,
id_item int not null,
posicao_x decimal(10,4) not null,
posicao_y decimal(10,4) not null,
posicao_z decimal(10,4) not null,
coletado boolean,
constraint fk_inventario_item foreign key (fk_inventario_item) references inventario_item (id_inventario)
);


drop table inventario_item;


CREATE TABLE inventario_item (
id_inventario_item int generated by default as identity primary key,
fk_save_state int not null,
id_item int not null,
slot_posicao int not null,
quantidade int not null,
constraint fk_save_state foreign key (fk_save_state) references save (id_save)
);


drop table jogador;


CREATE TABLE jogador (
  id_jogador int generated by default as identity primary key,
  fk_partida int    not null,
  nickname varchar(50) not null,
  email varchar(100) not null,
  senha_hash varchar(255) not null,
  tipo_perfil varchar(30) not null,
  total_partidas_jogadas int,
  total_vitorias int,
  data_cadastro timestamp,
  constraint fk_partida foreign key (fk_partida) references partida (id_partida)
);



CREATE TABLE save_state (
id_save int generated by default as identity primary key,
id_partida int not null,
vida_atual decimal(5,2) not null,
fome_atual decimal(5,2) not null,
sede_atual decimal(5,2) not null,
posicao_x decimal(10,4) not null,
posicao_y decimal(10,4) not null,
posicao_z decimal(10,4) not null,
capacidade_maxima_peso decimal(6,2) not null,
data_salvamento timestamp
);

CREATE TABLE reporte_bug (
id_reporte int generated by default as identity primary key,
id_jogador int not null,
titulo varchar(150) not null,
descricao text not null,
status varchar(30) not null,
data_envio timestamp
);
